  function smartTitle(str) {
    if (str == null) return str;
    return String(str).split(/(\s+)/).map(function (seg) {
      if (/^\s+$/.test(seg) || seg === "") return seg;
      return seg.split("-").map(function (part) {
        return /^[a-z]+$/.test(part) ? part.charAt(0).toUpperCase() + part.slice(1) : part;
      }).join("-");
    }).join("");
  }

  // valueLabel(value, fallbackText?) — curated label for a stored value, else a
  // smart-title of fallbackText (or the value itself when no fallback given).
  function valueLabel(value, fallbackText) {
    if (value != null && Object.prototype.hasOwnProperty.call(VALUE_LABELS, value)) {
      return VALUE_LABELS[value];
    }
    return smartTitle(fallbackText != null ? fallbackText : value);
  }

  window.VALUE_LABELS = VALUE_LABELS;
  window.smartTitleCase = smartTitle;
  window.valueLabel = valueLabel;
